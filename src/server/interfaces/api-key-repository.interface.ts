/**
 * @fileoverview Persistence contract and value types for scoped service API keys.
 *
 * The host implements {@link IApiKeyRepository} against its own store, as it does for users.
 * Nothing here is reversible: a row carries the HMAC digest of the secret and never the secret.
 *
 * @layer Interface
 */

/** One stored service key. */
export interface AuthApiKey {
  /** Row id, a lowercase UUID. It is the public half of the key a caller presents. */
  id: string
  /**
   * Human name for the machine caller this key belongs to. NOT unique: several active keys may
   * share one label, which is what makes an overlapping rotation possible.
   */
  label: string
  /** Lowercase hex HMAC-SHA-256 of the secret under the pepper. 64 characters. */
  digest: string
  /** Scopes this key holds. A route is admitted only when the key holds every scope it declares. */
  scopes: readonly string[]
  /** When the key was issued. */
  createdAt: Date
  /** The key stops verifying at this instant, when set. */
  expiresAt: Date | null
  /** When set, the key no longer verifies, on every instance, whatever instant it holds. */
  revokedAt: Date | null
  /** Last time the key verified. Advisory and coalesced: see `apiKeys.lastUsedFlushSeconds`. */
  lastUsedAt: Date | null
}

/** A stored key without its digest: what an operator-facing call may return or log. */
export type AuthApiKeySummary = Omit<AuthApiKey, 'digest'>

/** What the verified request carries as `request.apiKey`. */
export interface ApiKeyPrincipal {
  /** The key's row id: the stable handle to bucket a rate limit on after verification. */
  readonly id: string
  /** The machine caller's label. */
  readonly label: string
  /** The scopes the key holds. */
  readonly scopes: readonly string[]
}

/**
 * Persistence port for service API keys.
 *
 * @remarks
 * The library supplies `id` and `digest`; the store only persists them. Verification reads one
 * row per request, so `findById` should be a primary-key lookup.
 */
export interface IApiKeyRepository {
  /**
   * Finds a key by its row id.
   *
   * @param id - The id embedded in the presented key.
   * @returns The row, or `null` when none exists. Revoked and expired rows are still returned:
   *   the library decides validity, so every refusal takes the same steps.
   */
  findById(id: string): Promise<AuthApiKey | null>

  /**
   * Inserts a new key.
   *
   * @param row - The row to store. `id` is generated by the library.
   * @returns The stored row.
   */
  create(row: {
    id: string
    label: string
    digest: string
    scopes: readonly string[]
    createdAt: Date
    expiresAt: Date | null
  }): Promise<AuthApiKey>

  /**
   * Marks a key revoked.
   *
   * @param id - The key to revoke.
   * @param at - The instant it stops verifying.
   * @returns `false` when no such key exists. Revoking an already revoked key is not an error.
   */
  markRevoked(id: string, at: Date): Promise<boolean>

  /**
   * Sets when a key stops verifying. Used by rotation to retire the old key after an overlap.
   *
   * @param id - The key to change.
   * @param at - The new expiry instant.
   * @returns `false` when no such key exists.
   */
  setExpiry(id: string, at: Date): Promise<boolean>

  /**
   * Records when keys were last used, in one batch.
   *
   * MUST be monotonic: never move `lastUsedAt` backwards (`GREATEST(last_used_at, :at)`, or a
   * `WHERE last_used_at < :at` guard). Several instances flush independently, and a late flush
   * from one must not overwrite a newer value written by another.
   *
   * @param entries - One entry per key, the most recent use seen by this process.
   */
  touchLastUsed(entries: ReadonlyArray<{ id: string; at: Date }>): Promise<void>

  /**
   * Lists every key that carries a label, active or not.
   *
   * @param label - The machine caller's label.
   */
  listByLabel(label: string): Promise<AuthApiKey[]>
}
